"""
Decision Layer：莲心AI 的三层架构决策引擎
判断用户消息走"纯聊天"还是"全 Agent（带工具）"路由。

路由模式：
- chat_only:   所有消息走纯聊天，禁用工具
- force_agent: 所有消息走全 Agent，强制工具
- auto (默认): 规则匹配判断意图
"""

import re
from typing import Literal

RouteMode = Literal["auto", "chat_only", "force_agent"]

# ── 命中这些模式的消息走 Agent（需要调用工具） ──────────────

_AGENT_PATTERNS = [
    # 文件/代码操作
    r"(?:帮我|帮我)\s*(?:写|创建|生成|新建|编|改|修|删|读|打|编辑|修改|删除|重命名|复制|移动).*(?:文件|代码|脚本|程序|函数|类|模块|文档|笔记|Python|excel|word|docx|txt)",
    r"(?:读文件|读取|阅读|查看).*(?:文件|文档|内容|代码)",
    r"(?:写文件|写入文件|保存文件|写到)",
    r"(?:搜索|查找|找一下|找找).*(?:文件|代码|文件夹|目录|图片)",
    r"(?:列出|显示|查看).*(?:目录|文件夹|文件列表|桌面)",
    r"【指令】",

    # 网络/搜索
    r"(?:搜索|查一下|查查|查一查|搜一下|搜一搜|搜搜|百度)\s",
    r"搜索\s",
    r"查(?:一下|查|看)?\s*$",
    r"(?:查|看|搜|搜一搜|查一查).*(?:新闻|天气|资讯|消息|百度|网页)",
    # 事实核验：即使用户没有直接说“搜索”，也必须进入 Agent，
    # 由工具层取得真实来源，避免模型仅凭上下文补全答案。
    r"(?:原文|文章|网页|资料).*(?:是否|有没有|是否真的|声称|提到|准确|属实)",
    r"(?:具体|到底|究竟).*(?:多少|几条|哪一天|什么时候|哪个版本)",
    r"(?:准确吗|是真的吗|属实吗|是不是编造|是不是胡编|不要胡编|不要编造|重新核对|重新核实|核对一下|核实一下)",

    # 应用/系统操作
    r"(?:打开|启动|运行|帮我开|帮我打开|帮我启动).*(?:应用|程序|软件|游戏|计算器|记事本|画图|命令行|微信|qq|网易云|steam)",
    r"打开\S+",  # "打开记事本"、"打开微信"

    # 待办/提醒/闹钟
    r"(?:提醒我|添加待办|记一下|别忘了|添加提醒|设置提醒|定时|计划任务|闹钟)",
    r"(?:待办列表|查看待办|有什么待办|列出待办|完成待办|标记完成)",

    # 记忆
    r"(?:记住|记下来|保存到记忆|存到记忆|查一下记忆|搜索记忆)",

    # 余额
    r"(?:余额|还剩多少钱|还有多少钱|欠费)",

    # 音乐
    r"(?:播放|暂停|下一首|上一首|音量|歌单|放歌|听歌|音乐)",
    r"(?:放什么歌|播放状态|现在在放|什么歌|当前播放)",

    # 图片/视觉/肩载观察
    r"(?:拍照|摄像头|拍一张|看(?:看|一眼))",
    r"(?:图片|图像|画面).*(?:分析|识别|描述|理解)",
    r"(?:观察|看看|扫描|环顾).*(?:四周|周围|环境|一下|一圈)",
    r"(?:启动|开始).*(?:观察|探索|扫描)",

    # OCR/截图
    r"(?:OCR|文字识别|提取文字|截图|截屏)",

    # 发送到 QQ
    r"(?:发给我|发送文件|发到qq|发到QQ|传到QQ|把文件.*(?:发给|发到))",

    # 备忘本
    r"(?:备忘本|查看备忘|整理备忘|读备忘)",

    # Excel/Word 操作
    r"(?:Excel|excel|xlsx|Word|docx|写入表格|读取表格)",

    # 跨端搜索
    r"(?:另一端|另一边|桌面端|QQ端).*(?:说|提|聊|搜索)",
    # 对话历史回顾（必须查真实会话记录）
    r"(?:最近|昨天|前天|之前|上次|这几天).*(?:聊了|聊过|说了|说过).*(?:什么|啥|内容|事情)?",
    r"(?:我们|咱们).*(?:最近|昨天|前天|之前|上次).*(?:聊|说)",

    # 翻译
    r"(?:翻译|翻译一下|翻一下).*(?:中文|英文|日文|法文|翻译成)",

    # 日记
    r"(?:日记|写日记|读日记|查日记|回忆\S*日)",

    # 主动聊天控制
    r"(?:开启|关闭|启用|停用|禁用).*(?:主动聊天|主动)",

    # 时间/日期查询
    r"(?:现在|当前|今天|明天|昨天).*(?:几点|几时|时间|日期|星期|号)",
    r"(?:几点了|几时了|现在几点|今天几号|星期几|什么日期|什么时间)",
    r"(?:农历|公历|阳历|阴历)\s*(?:日期|时间|几号|几月)",
    r"(?:今年|明年|去年).*(?:什么年|哪一年)",
    r"(?:还有几天|倒计时|距离).*(?:到|才|就).*(?:还有|还剩)",
    r"(?:三月三|清明节|端午节|中秋节|春节|元宵节|国庆节|劳动节|元旦).*(?:几号|时候|假期|放假|是.*日)",
    r"(?:节日|节气|农历|过年).*(?:什么时候|几月几号|到了吗|过了吗)",

    # 天气查询
    r"(?:天气|气温|温度|多少度|冷不冷|热不热|下(?:雨|雪|冰雹)|刮风|出太阳|天晴|天阴|雾霾|台风|沙尘|空气质量|AQI|湿度)",
    r"(?:今天|明天|后天|昨天|这(?:几|两)天|未来|这周|周末).*(?:天气|气温|温度|下雨|下雪|刮风|多少度)",
    r"(?:查|看|问|查查|看看|问问|搜一下).*(?:天气|气温|温度|下雨|下雪)",
    r"(?:带伞|加衣服|穿什么|加衣|保暖|防暑|防晒|出行建议)",
    r"^(?:天气|气温|温度|下雨|下雪|刮风|多少度|冷不冷|热不热)",
    r"(?:我在|我住在|我目前|我现在).*(?:市|省|区|县|城市|地方)",

    # 通用命令前缀（拼音/中文）
    r"^(?:请\s*)?(?:帮我|帮我|帮我做|帮我写|帮我查|帮我找|帮我弄|帮我弄一下|帮我处理)",
    r"^(?:请\s*)?(?:创建|新建|生成|写一个|写一段|写一篇|编写|编一个)",
]


def decide(
    user_input: str,
    *,
    route_mode: RouteMode = "auto",
) -> str:
    """
    判断用户消息应该走哪条路由。

    参数:
        user_input: 用户消息文本
        route_mode: 路由模式
            - "auto":       自动判断
            - "chat_only":  强制纯聊天（不走工具）
            - "force_agent": 强制全 Agent（走工具）

    返回:
        "chat" 或 "agent"
    """
    if route_mode == "chat_only":
        return "chat"
    if route_mode == "force_agent":
        return "agent"

    # auto 模式：规则匹配
    cleaned = user_input.strip()
    if not cleaned:
        return "chat"

    if _matches_any_pattern(cleaned, _AGENT_PATTERNS):
        return "agent"

    return "chat"


def _matches_any_pattern(text: str, patterns: list[str]) -> bool:
    """检查文本是否匹配任意一个正则模式。"""
    return any(re.search(pattern, text) for pattern in patterns)
